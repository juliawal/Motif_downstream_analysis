#!/usr/bin/env python3
"""Render the supplementary overview of pipeline evaluations and downstream use.

The table contains fixed methodological descriptions; no results are evaluated
or statistical tests run. Edit OVERVIEW to update the descriptions. The
manuscript places this table in a landscape environment.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

OVERVIEW = r'''% Generated by scripts/tables/build_evaluation_overview.py.
\begin{table}[!htbp]
\centering
\footnotesize
\caption{Biological evaluation in the Motif pipeline and downstream analysis of its results.}
\label{tab:evaluation-overview}
\setlength{\tabcolsep}{5pt}
\renewcommand{\arraystretch}{1.0}
\begin{tabular}{@{}>{\raggedright\arraybackslash}p{\dimexpr.11\linewidth-1.5\tabcolsep\relax}>{\raggedright\arraybackslash}p{\dimexpr.24\linewidth-1.5\tabcolsep\relax}>{\raggedright\arraybackslash}p{\dimexpr.35\linewidth-1.5\tabcolsep\relax}>{\raggedright\arraybackslash}p{\dimexpr.30\linewidth-1.5\tabcolsep\relax}@{}}
\toprule
\textbf{Stage} & \textbf{What the Motif pipeline does} & \textbf{Results from the Motif pipeline} & \textbf{Downstream analysis} \\
\midrule
\textbf{F1} \newline Binding-site evaluation
& Tests if potential binding sites occur more frequently near candidate MFs' selected CpGs than near matched background CpGs, using motif matches or ChIP-seq overlaps~\cite{Johnson2007}.
& Hit counts and hit rates for each MF's selected and background CpGs. Hit rates are the proportions of CpG windows containing a binding hit. Median hit-rate differences and group sign-test $p$-values are saved separately for motif matches and ChIP-seq overlaps.
& Compares individual hit rates and their differences in percentage points between settings. Summarises binding-data coverage and compares group-test results across cohorts (\Cref{sec:results-binding}). \\
\addlinespace[0.6em]
\textbf{F2} \newline PPI network proximity
& Measures candidate proteins' proximity to DNMT/TET enzymes using PageRank and harmonic centrality. Compares the candidate group with degree-matched random groups.
& For each measure: group $p$-values, individual MF scores, matched-background mean scores and MF contributions. A score difference is the MF's score minus its background mean. Each MF contribution is its share of the sum of positive score differences within the candidate list.
& Adds the three largest MF contributions per cohort and measure. Compares group-test results between settings and cohorts (\Cref{sec:results-ppi-proximity}). Calculates individual score differences from the background mean in percent. \\
\addlinespace[0.6em]
\textbf{F3} \newline Gene-set enrichment
& Tests whether the candidate list contains more genes linked to a biological term than expected from the background genes.
& For each tested term: its $p$-value, BH-adjusted $p$-value, fold enrichment and candidate MFs linked to it. Fold enrichment compares the proportion of candidate MFs linked to the term with the corresponding proportion of background genes.
& Retains terms with a BH-adjusted $p$-value $\leq0.05$ and at least three candidate MFs. Summarises their functions, compares settings and cohorts, and examines their candidate MFs (\Cref{sec:results-functional-enrichment}). \\
\addlinespace[0.6em]
\textbf{F4} \newline Mediation
& Tests associations between MF expression, CpG methylation and the expression of a nearby gene $G'$. Each combination forms an MF--CpG--$G'$ triplet.
& Regression coefficients and test results for each testable triplet, including the BY-adjusted joint $p$-value and whether the triplet is supported. A triplet is supported if this adjusted $p$-value is $\leq0.05$. Coefficient $a$ describes the MF expression--methylation association.
& Counts an MF--CpG pair as supported when at least one triplet is supported. Calculates supported/tested pair counts and proportions per MF, cohort and setting (\Cref{sec:results-associations}). Compares the sign of $a$ for the same pair across cohorts, regardless of F4 support (\Cref{sec:results-exact-directions}). \\
\bottomrule
\end{tabular}
\par\smallskip
\begin{minipage}{\linewidth}
\footnotesize
F1 and F2 $p$-values assess candidate groups; F3 $p$-values assess functional terms; F4 $p$-values assess triplets. The downstream analyses use the saved results without additional significance tests for individual MFs. BH: Benjamini--Hochberg correction; BY: Benjamini--Yekutieli correction.
\end{minipage}
\end{table}
'''


def render_evaluation_overview(output):
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(OVERVIEW, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path,
        default=ROOT / "tables/supplement/evaluation_overview.tex",
    )
    args = parser.parse_args()
    render_evaluation_overview(args.output)
    print(f"Wrote the evaluation overview: {args.output}")


if __name__ == "__main__":
    main()
